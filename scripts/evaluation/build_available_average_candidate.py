"""Available-source average transfer candidate on the full H1 axis (all 126 targets).

For target t and gene g, average the c = 10 CPM log changes log((kp+c)/(k0+c)) over the
five anchor sources that measure both t and g; missing entries are not zeros, and a gene
no source measures keeps factor 1. Source CPMs are the frozen per-source `available_*`
profiles (each normalized on its own source-H1 shared genes). The destination is H1's
pooled control CPM on all 18,080 genes. One fold-change-space scale a is cross-fitted
over five folds of the 126 targets (all target genes excluded from the loss), then cells
are generated by h1_generation (dependent rounding with a fidelity check).
Run: pixi run python -m scripts.evaluation.build_available_average_candidate OUT.h5ad
"""

from __future__ import annotations

import argparse
import json

import numpy as np
import pandas as pd

import scripts.evaluation.h1_transfer_regression as reg
from scripts.evaluation.h1_generation import generate
from scripts.evaluation.kolf_h1_transfer_rules import cpm

C = 10.0
ANCHORS = ("K562_GWPS", "CD4T", "HCT116", "HEK293T", "KOLF2.1J")
H1 = reg.ROOT / "data/derived/replogle_h1_transfer/effects.npz"
PHASE1 = reg.ROOT / "data/derived/replogle_h1_transfer/phase1_effects.npz"
REPORT = reg.ROOT / "reports/h1-transfer-regression/available_average"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output")
    parser.add_argument("--pseudocount", type=float, default=C, help="transfer pseudocount c (CPM)")
    parser.add_argument("--direct", action="store_true", help="a = 1 instead of the fitted scale")
    parser.add_argument("--wrong-target", action="store_true", help="with --direct: deranged donor targets")
    args = parser.parse_args()
    c = args.pseudocount
    suffix = "" if c == C else f"_c{c:g}"
    REPORT.mkdir(parents=True, exist_ok=True)
    with np.load(PHASE1) as a:
        targets = a["target_gene"].astype(str)
        genes = a["output_gene"].astype(str)
    with np.load(H1) as a:
        assert (a["target_gene"].astype(str) == targets).all()
        h0 = cpm(a["h1_control_count_sum"])
        hp = cpm(a["h1_count_sum"])
    ti = {t: i for i, t in enumerate(targets)}
    gi = {g: i for i, g in enumerate(genes)}
    total = np.zeros(hp.shape)
    count = np.zeros(hp.shape, dtype=int)
    for s in ANCHORS:
        with np.load(reg.SOURCE / f"available_{s}/{s}.npz") as z:
            r = np.array([ti[t] for t in z["targets"].astype(str)])
            g = np.array([gi[x] for x in z["genes"].astype(str)])
            change = reg.direction(z["source_perturbed"], z["source_control"], c)
        total[np.ix_(r, g)] += change
        count[np.ix_(r, g)] += 1
    d = np.divide(total, count, out=np.zeros_like(total), where=count > 0)
    coverage = pd.DataFrame(
        {"target_gene": targets, "sources_max": count.max(axis=1), "genes_covered": (count > 0).sum(axis=1)}
    )
    coverage.to_csv(REPORT / "coverage.csv", index=False)

    strong = pd.read_csv(reg.STRONG).query("stable_strong")
    common = {"targets": targets, "genes": genes, "h1_control": h0, "h1_truth": hp}
    panel = reg.Panel("available_average", {}, common, strong)
    direct = panel.score(panel.effect(reg.realize(d, h0, c)))
    frame, row, coefs = reg.run_fold_change_scale(panel, c, "available_avg:scaled", d)
    a_fold = np.array([c["value"] for c in coefs])
    summary = pd.DataFrame(
        [
            {"model": "available_avg:direct", **direct.drop(columns=["squared_error", "truth_energy", "strong_genes"]).mean(),
             "profile_mse_ratio": direct.squared_error.sum() / direct.truth_energy.sum()},
            {**row},
        ]
    )
    summary.to_csv(REPORT / f"summary{suffix}.csv", index=False)
    frame.assign(target_gene=targets).to_csv(REPORT / f"per_target_scaled{suffix}.csv", index=False)
    print(summary[["model", "retrieval", "cosine", "profile_mse_ratio"]].to_string(), flush=True)
    print("fold a:", np.round(a_fold, 4), flush=True)

    profiles = np.empty_like(hp)
    for f in range(reg.FOLDS):
        test = panel.fold == f
        profiles[test] = reg.realize(d[test], h0, c, a_fold[f])
    # Positive control: the realized profiles reproduce the cross-fitted held-out error.
    check = panel.score(panel.effect(profiles))
    np.testing.assert_allclose(
        check.squared_error.sum() / check.truth_energy.sum(), row["profile_mse_ratio"], rtol=1e-9
    )
    name = "available_avg_scaled"
    if args.direct:  # unscaled transfer; its held-out metrics are in summary.csv as :direct
        name = "available_avg_direct"
        change = d
        if args.wrong_target:  # negative control: each target gets another target's donor change
            name = "available_avg_direct_wrong_target"
            rng = np.random.default_rng(reg.SEED + 7)
            perm = rng.permutation(len(targets))
            while np.any(perm == np.arange(len(targets))):
                perm = rng.permutation(len(targets))
            change = d[perm].copy()
            donor_gene = np.array([gi[targets[j]] for j in perm])
            change[np.arange(len(targets)), donor_gene] = 0.0  # no leaked donor knockdown
        profiles = reg.realize(change, h0, c, 1.0)
    with np.errstate(divide="ignore", invalid="ignore"):
        factor = np.where(h0 > 0, np.log2(profiles / h0), 0.0)
    name = name + suffix
    info = generate(name, factor, args.output, reg.ROOT / "reports/h1-transfer-regression/cell_eval_v3" / name)
    info.update({"pseudocount": c, "anchors": ANCHORS, "fold_a": None if args.direct else a_fold.tolist()})
    (REPORT / f"generation_{name}.json").write_text(json.dumps(info, indent=1))

if __name__ == "__main__":
    main()
